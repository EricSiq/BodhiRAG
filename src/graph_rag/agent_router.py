"""
Hybrid RAG Agent: Dynamic query routing with LLM-powered answer synthesis.
Combines Knowledge Graph reasoning (Neo4j) with Vector Store retrieval (ChromaDB).
Answers are generated by Mistral-7B-Instruct via HF Inference API.
"""

import time
from typing import Dict, List, Any, Optional, TypedDict
import logging

logger = logging.getLogger(__name__)


class RouterState(TypedDict):
    """State definition for the hybrid RAG router."""
    query: str
    query_type: str
    kg_results: List[Dict]
    vs_results: List[Dict]
    final_answer: str
    reasoning_path: List[str]


class HybridRAGAgent:
    """
    Routes queries intelligently between Knowledge Graph and Vector Store,
    then synthesizes answers using an LLM.
    """

    def __init__(self, kg_connector, vs_connector):
        self.kg_connector = kg_connector
        self.vs_connector = vs_connector

        # Lazy import to avoid circular imports and slow startup
        self._llm_generate = None

        # Query classification patterns
        self.kg_query_patterns = [
            "relationship", "effect", "cause", "impact", "influence",
            "how does", "what causes", "what affects", "mechanism",
            "interaction", "pathway", "network", "link between",
            "connection", "associated with",
        ]
        self.vs_query_patterns = [
            "describe", "what is", "explain", "overview", "summary",
            "information about", "details about", "tell me about",
            "background", "introduction", "review",
        ]

    # ------------------------------------------------------------------
    # LLM access (lazy-loaded)
    # ------------------------------------------------------------------

    def _get_llm(self):
        """Lazy-load the LLM inference function."""
        if self._llm_generate is None:
            try:
                from src.services.llm_inference import generate_answer
                self._llm_generate = generate_answer
            except ImportError:
                logger.warning("LLM inference module not available: using fallback")
                self._llm_generate = self._template_fallback
        return self._llm_generate

    # ------------------------------------------------------------------
    # Query routing
    # ------------------------------------------------------------------

    def classify_query_intent(self, query: str) -> str:
        """Classify query intent to choose the best retrieval strategy."""
        q = query.lower()
        if any(p in q for p in self.kg_query_patterns):
            return "kg_primary"
        if any(p in q for p in self.vs_query_patterns):
            return "vs_primary"
        return "hybrid"

    def route_query(
        self,
        query: str,
        use_kg: bool = True,
        use_vector: bool = True,
    ) -> dict:
        """
        Route a query and return a full result dict including LLM answer.
        """
        logger.info(f"Routing query (KG={use_kg}, VS={use_vector}): {query!r}")

        # Determine query type
        if use_kg and not use_vector:
            query_type = "kg_primary"
        elif use_vector and not use_kg:
            query_type = "vs_primary"
        else:
            query_type = self.classify_query_intent(query)

        start_time = time.time()
        kg_time = 0.0
        vs_time = 0.0

        # Execute retrieval
        kg_results: List[Dict] = []
        vs_results: List[Dict] = []
        entities_found: List[str] = []

        if use_kg:
            t0 = time.time()
            entities_found = self._extract_entities_from_query(query)
            kg_results = self.execute_kg_retrieval(query)
            kg_time = time.time() - t0

        if use_vector:
            t1 = time.time()
            vs_results = self.execute_vs_retrieval(query, n_results=5)
            vs_time = time.time() - t1

        t2 = time.time()
        # Generate answer with LLM (Qwen 3.5 default)
        final_answer = self._get_llm()(query, kg_results, vs_results)
        gen_time = time.time() - t2
        total_latency = time.time() - start_time

        return {
            "query": query,
            "query_type": query_type,
            "entities_extracted": entities_found,
            "kg_results": kg_results,
            "vs_results": vs_results,
            "final_answer": final_answer,
            "retrieval_stats": {
                "kg_relationships": len(kg_results),
                "vs_documents": len(vs_results),
                "kg_latency_ms": round(kg_time * 1000, 1),
                "vs_latency_ms": round(vs_time * 1000, 1),
                "generation_latency_ms": round(gen_time * 1000, 1),
                "total_latency_ms": round(total_latency * 1000, 1),
            },
        }

    # ------------------------------------------------------------------
    # Retrieval methods
    # ------------------------------------------------------------------

    def execute_kg_retrieval(self, query: str) -> List[Dict]:
        """Retrieve knowledge graph relationships relevant to the query."""
        try:
            entities = self._extract_entities_from_query(query)
            kg_results: List[Dict] = []
            for entity in entities:
                relationships = self.kg_connector.query_relationships(entity)
                kg_results.extend(relationships)
            logger.info(f"KG retrieval: {len(kg_results)} relationships for {entities}")
            return kg_results
        except Exception as e:
            logger.error(f"KG retrieval failed: {e}")
            return []

    def execute_vs_retrieval(self, query: str, n_results: int = 5) -> List[Dict]:
        """Retrieve semantically similar documents from the vector store."""
        try:
            results = self.vs_connector.semantic_search(query, n_results)
            logger.info(f"VS retrieval: {len(results)} documents")
            return results
        except Exception as e:
            logger.error(f"VS retrieval failed: {e}")
            return []

    # ------------------------------------------------------------------
    # Entity extraction
    # ------------------------------------------------------------------

    def _extract_entities_from_query(self, query: str) -> List[str]:
        """
        Extract biomedical entity names from the query using a curated
        term list plus simple multi-word phrase extraction.
        """
        space_biology_entities = [
            "microgravity", "radiation", "bone loss", "bone density", "osteoporosis",
            "muscle atrophy", "muscle wasting", "oxidative stress", "reactive oxygen species",
            "stem cells", "immune system", "cardiovascular", "neurovestibular",
            "tissue regeneration", "gene expression", "epigenetics", "telomere",
            "circadian rhythm", "fluid shift", "intracranial pressure", "vision",
            "cognitive function", "sleep", "exercise countermeasure",
            "vitamin d", "calcium", "phosphorus", "osteoclast", "osteoblast",
            "astronaut", "cosmonaut", "iss", "space station",
            "spaceflight", "launch", "reentry", "long duration",
            "dna damage", "dna repair", "chromosome", "mutation",
        ]

        q = query.lower()
        found: List[str] = []

        # Match curated entities
        for entity in space_biology_entities:
            if entity in q:
                found.append(entity)

        # Fallback: extract 2-word phrases as candidate entities
        if not found:
            words = q.split()
            bigrams = [" ".join(words[i : i + 2]) for i in range(len(words) - 1)]
            found = [b for b in bigrams if len(b) > 5]

        return found if found else ["space biology"]

    # ------------------------------------------------------------------
    # Legacy interface (backward compatibility)
    # ------------------------------------------------------------------

    def query(self, user_query: str) -> Dict[str, Any]:
        """Legacy single-string query interface."""
        return self.route_query(user_query, use_kg=True, use_vector=True)

    # ------------------------------------------------------------------
    # Static fallback (when LLM module unavailable)
    # ------------------------------------------------------------------

    @staticmethod
    def _template_fallback(query: str, kg_results: list, vs_results: list) -> str:
        lines = [f"**Research on:** {query}\n"]
        if kg_results:
            lines.append("**Key Relationships:**")
            for r in kg_results[:4]:
                lines.append(f"• {r.get('subject')} → {r.get('relationship')} → {r.get('object')}")
        if vs_results:
            lines.append("\n**From the Literature:**")
            for doc in vs_results[:2]:
                lines.append(f"• {doc.get('content', '')[:200]}...")
        if not kg_results and not vs_results:
            lines.append("No information found. Please run the data pipeline first.")
        return "\n".join(lines)


# Backward compatibility alias
AgentRouter = HybridRAGAgent